def main() -> None:
    movies = [
        Movie(
            id=mid,
            title=title,
            original_title=orig,
            year=year,
            runtime=runtime,
            genres=genres,
            rating=rating,
            votes=20_000,
            score=round(rating - 0.15, 3),
            poster=None,
            overview=f"{pitch} (sinopse de exemplo — rode o pipeline para os dados reais)",
            providers=[],
            vibes=heuristic_vibes(genres),
            pitch=pitch,
        )
        for mid, title, orig, year, runtime, genres, rating, pitch in MOVIES
    ]
    catalog = Catalog(
        generated_at="2026-11-08T00:00:00+00:00",
        genres=GENRES,
        vibes=VIBES,
        providers={},
        movies=sorted(movies, key=lambda m: m.score, reverse=True),
    )
    out = Path("web/public/data/catalog.sample.json")
    data = catalog.model_dump(mode="json", exclude_none=True) | {"sample": True}
    out.write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")
    print(f"Wrote {len(movies)} sample movies to {out}")


if __name__ == "__main__":
    main()
